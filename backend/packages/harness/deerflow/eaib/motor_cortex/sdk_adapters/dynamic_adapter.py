"""DynamicSdkAdapter — a runtime-generated adapter for any robot hardware.

运动皮层 (Motor Cortex): codegen-friendly adapter.

When a user describes their robot, the motor cortex agent:
1. Converses with the user to understand the hardware and SDK
2. Generates Python code for the five adapter methods
3. Calls `DynamicSdkAdapter.from_spec()` to create an in-memory adapter
4. Calls `AdapterRegistry.register()` to persist it to disk
5. From then on it is loaded automatically via `AdapterRegistry.load_all()`

The generated code is stored at:
  ~/.local/share/eaib/adapters/<body_id>/adapter.py

It must export a top-level class named `Adapter(BaseSdkAdapter)`.
"""

